// Cs2Kotlin - translate the generated C# SWMM6 engine (cs/gen) into Kotlin (kotlin/gen/engine), using Roslyn's
// semantic model. It is the Java translator (Cs2Java.cs, JavaTypes.cs, JavaFn.cs) copied and changed where Kotlin
// differs from Java: the same names, the same runtime calls (the Kotlin runtime, kotlin/src/cpp, has the Java runtime's
// shape) and the same analysis, written in Kotlin's syntax with Kotlin's rules. The mapping is recorded in KOTLIN.md.
//
//   dotnet bin/cs2kotlin.dll CS_DIR KOTLIN_GEN_DIR
//
// Written by Claude (Anthropic) for Robert Dickinson's SWMM6 ports; see AI-USE.md and kotlin/README.md.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

public sealed class Todo : Exception { public Todo(string m) : base(m) { } }

public static partial class Cs2Kotlin
{
    static CSharpCompilation comp = null!;
    static readonly Dictionary<SyntaxTree, SemanticModel> models = new();
    static SemanticModel M(SyntaxNode n) => models[n.SyntaxTree];
    static readonly SortedDictionary<string, int> todos = new();
    static readonly SortedDictionary<string, string> manifest = new();   // runtime member used -> its Java name

    public static int Main(string[] args)
    {
        var cs = args[0];
        var outDir = args[1];
        var files = Directory.GetFiles(Path.Combine(cs, "gen"), "*.cs").Concat(Directory.GetFiles(Path.Combine(cs, "runtime"), "*.cs"))
            .Where(f => !f.EndsWith("Program.cs")).OrderBy(f => f, StringComparer.Ordinal).ToArray();
        var opts = new CSharpParseOptions(LanguageVersion.Latest);
        var trees = files.Select(f => CSharpSyntaxTree.ParseText(File.ReadAllText(f), opts, f)).ToList();
        var fw = Path.GetDirectoryName(typeof(object).Assembly.Location)!;
        var refs = new List<MetadataReference>();
        foreach (var f in Directory.GetFiles(fw, "*.dll"))
        {
            var b = Path.GetFileName(f);
            if (b.StartsWith("Microsoft.VisualBasic") || b == "mscorlib.dll") continue;
            try { refs.Add(MetadataReference.CreateFromFile(f)); } catch { }
        }
        comp = CSharpCompilation.Create("engine", trees, refs, new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));
        var errs = comp.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
        if (errs.Count > 0) { foreach (var e in errs.Take(10)) Console.Error.WriteLine(e); return 1; }
        foreach (var t in trees) models[t] = comp.GetSemanticModel(t);
        var gen = trees.Where(t => t.FilePath.Contains("/gen/") || Path.GetFileName(t.FilePath).StartsWith("Hand_")).ToList();

        var pkgDir = Path.Combine(outDir, "engine");
        Directory.CreateDirectory(pkgDir);
        foreach (var f in Directory.GetFiles(pkgDir, "*.kt")) File.Delete(f);
        CollectTypes(gen);
        foreach (var g in engineTypes.GroupBy(TypeIdent).Where(g => g.Count() > 1)) Note("two types named " + g.Key);
        Analyze(gen);
        foreach (var s in engineTypes)
        {
            var sb = new StringBuilder();
            sb.Append(FileHeader);
            try { TypeDecl(s, sb); }
            catch (Todo e) { sb.Append("// TODO ").Append(e.Message).Append('\n'); }
            File.WriteAllText(Path.Combine(pkgDir, TypeIdent(s) + ".kt"), sb.ToString());
        }
        foreach (var kv in extraFiles) File.WriteAllText(Path.Combine(pkgDir, kv.Key + ".kt"), kv.Value);
        using (var w = new StreamWriter(Path.Combine(outDir, "..", "cs2kotlin_todo.txt")))
            foreach (var kv in todos.OrderByDescending(kv => kv.Value)) w.WriteLine("{0,6}  {1}", kv.Value, kv.Key);
        using (var w = new StreamWriter(Path.Combine(outDir, "..", "cs2kotlin_runtime.txt")))
            foreach (var kv in manifest) w.WriteLine(kv.Key + "\t" + kv.Value);
        Console.WriteLine("wrote " + Directory.GetFiles(pkgDir, "*.kt").Length + " files, " + todos.Count + " TODO kinds, " + todos.Values.Sum() + " TODO sites");
        return 0;
    }

    static readonly SortedDictionary<string, string> extraFiles = new();

    public const string FileHeader = "// Code generated by tools/cs2x/Cs2Kotlin.cs from cs/gen. DO NOT EDIT.\n" +
        "@file:Suppress(\"UNCHECKED_CAST\", \"NAME_SHADOWING\", \"UNUSED_VARIABLE\", \"UNUSED_PARAMETER\", \"UNUSED_VALUE\", \"UNREACHABLE_CODE\",\n" +
        "    \"UNNECESSARY_NOT_NULL_ASSERTION\", \"USELESS_CAST\", \"REDUNDANT_PROJECTION\", \"VARIABLE_WITH_REDUNDANT_INITIALIZER\", \"ASSIGNED_BUT_NEVER_ACCESSED_VARIABLE\",\n" +
        "    \"KotlinConstantConditions\", \"FunctionName\", \"LocalVariableName\", \"ClassName\", \"PropertyName\", \"ObjectPropertyName\", \"DEPRECATION\", \"UNUSED_EXPRESSION\")\n\n" +
        "package engine\n\n";

    static void Note(string what) { todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1; }

    static string Todo(string what)
    {
        todos[what] = todos.TryGetValue(what, out var c) ? c + 1 : 1;
        throw new Todo(what);
    }

    static void Use(string key, string java) { manifest[key] = java; }

